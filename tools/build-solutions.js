'use strict';
const fs = require('node:fs');
const path = require('node:path');
const E = require('../engine.js');
const levels = require('../levels.js');
const { solve, expandSolution } = require('./solver.js');
const solutions = levels.map(source => {
  const level = E.parseLevel(source), result = solve(level, 1000000);
  if (!result.solved) throw new Error(`Room ${source.id} has no verified solution.`);
  return {
    fingerprint: level.map.join('/') + JSON.stringify([level.player, level.boxes]),
    solution: expandSolution(level, result.pushes)
  };
});
fs.writeFileSync(path.join(__dirname, '../solutions.js'),
  '/* Generated by tools/build-solutions.js. */\nwindow.BlueBoxSolutions = ' + JSON.stringify(solutions, null, 2) + ';\n');
console.log('PASS: Generated and replay-verified PPA solutions for all eight rooms.');
